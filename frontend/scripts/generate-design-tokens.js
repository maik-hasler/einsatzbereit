#!/usr/bin/env node

// Tailwind 4's `@theme` block in src/styles/global.css is where this project's
// design tokens live, and it should stay that way: it is the file someone
// editing a colour actually opens, and Tailwind reads it directly to build the
// utility classes.
//
// What it cannot do is hand a value to TypeScript. Four places need one anyway:
// the PWA manifests' `theme_color` (vite.config.ts, twice), index.html's
// `<meta name="theme-color">`, and `lib/brandColor.ts`, which used to read the
// custom property back out of the DOM with `getComputedStyle` - a browser
// round trip to learn a constant, and a DOM dependency in the folder that is
// supposed to have none.
//
// So: one source, one generated mirror. `pnpm tokens:generate` writes it,
// `pnpm check:design-tokens` fails CI when the two disagree.
//
// Deliberately not Style Dictionary. It would invert the direction - tokens in
// JSON, CSS generated from them - which makes the file a Tailwind developer
// edits a build artefact, to manage nineteen values. Its transforms and
// platform outputs start paying for themselves at a different order of
// magnitude, and on a day when there is a second platform to output to.

import { readFileSync, writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { join, dirname } from "path";
import prettier from "prettier";

const __dirname = dirname(fileURLToPath(import.meta.url));
const frontendDir = join(__dirname, "..");

const CSS_FILE = "src/styles/global.css";
const TS_FILE = "src/lib/designTokens.ts";

export function readThemeTokens() {
	const css = readFileSync(join(frontendDir, CSS_FILE), "utf8");
	const block = /@theme\s*\{([\s\S]*?)\n\}/.exec(css);
	if (!block) {
		throw new Error(
			`Could not find the @theme block in ${CSS_FILE}. It is the source of every design token; ` +
				"if it moved, update scripts/generate-design-tokens.js to match.",
		);
	}

	const tokens = {};
	for (const [, name, value] of block[1].matchAll(
		/^\s*(--[a-z0-9-]+):\s*([\s\S]*?);$/gm,
	)) {
		tokens[name] = value.replace(/\s+/g, " ").trim();
	}

	if (Object.keys(tokens).length === 0) {
		throw new Error(`The @theme block in ${CSS_FILE} parsed to zero tokens.`);
	}
	return tokens;
}

export async function renderModule(tokens) {
	const entries = Object.entries(tokens)
		.map(([name, value]) => `\t"${name}": ${JSON.stringify(value)},`)
		.join("\n");

	const source = `// Generated by scripts/generate-design-tokens.js - DO NOT EDIT.
//
// The source is the @theme block in src/styles/global.css. Change a value
// there and run \`pnpm tokens:generate\`; \`pnpm check:design-tokens\` fails CI
// when this file and that block disagree.

export const designTokens = {
${entries}
} as const;

export type DesignTokenName = keyof typeof designTokens;

/** The raw value of a token, by its CSS custom-property name. */
export function designToken(name: DesignTokenName): string {
\treturn designTokens[name];
}
`;

	// Formatted with the repo's own Prettier config so `pnpm format:check`
	// passes on the output and `check-design-tokens.js` can compare byte for
	// byte rather than guessing at whitespace.
	// `editorconfig: true` because indent_style lives in .editorconfig here,
	// not in .prettierrc.json - without it the output comes back space-indented
	// and `format:check` rejects a file this script just wrote.
	const config = await prettier.resolveConfig(join(frontendDir, TS_FILE), {
		editorconfig: true,
	});
	return prettier.format(source, { ...config, filepath: TS_FILE });
}

export { CSS_FILE, TS_FILE, frontendDir };

if (import.meta.url === `file://${process.argv[1]}`) {
	const tokens = readThemeTokens();
	writeFileSync(join(frontendDir, TS_FILE), await renderModule(tokens));
	console.log(
		`Wrote ${Object.keys(tokens).length} design tokens from ${CSS_FILE} to ${TS_FILE}.`,
	);
}
